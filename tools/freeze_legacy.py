#!/usr/bin/env python3
"""Writes test/legacy_core.h: verbatim copies of the core functions as they were BEFORE the performance work (git revision given with --rev, default the tag v0.4.10),
in namespace `legacy`. test/test_core.cpp runs the optimised functions against these on random inputs, so a speed-up can be shown not to change what they compute.

    python tools/freeze_legacy.py [--rev v0.4.10]

The functions are cut out of src/core.cpp of that revision by name (brace matching), so nothing is retyped.
"""
import argparse
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# in dependency order
WANTED = [
    "smoothstep01", "averageOf", "toHsv", "fromHsv", "vividBlendHsv", "applyTable", "saturateColours", "boxPassColours", "blurColours",
    "adjustZones", "easeColours", "packColours", "leadBoost", "decodeFrame", "frameChecksumOk", "classifyFrame", "finishColours", "darkOutside",
]
EXTRA_STRUCT = "struct Hsv { float h, s, v; };\n"


def cut(src, name):
    # a definition starts at column 0 and ends the line with "{"; the name is followed by "("
    pat = re.compile(r"^(?:static\s+)?(?:inline\s+)?[A-Za-z_][\w:<>\*&\s]*?\b" + re.escape(name) + r"\([^;{]*\)\s*(?:const\s*)?\{\s*$", re.M)
    m = pat.search(src)
    if not m:
        raise SystemExit("function %s not found" % name)
    i = src.index("{", m.start())
    depth = 0
    j = i
    while True:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    return src[m.start():j + 1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default="v0.4.10")
    a = ap.parse_args()
    src = subprocess.check_output(["git", "show", "%s:src/core.cpp" % a.rev], cwd=ROOT).decode()
    out = ["// GENERATED by tools/freeze_legacy.py from src/core.cpp at git revision %s - do not edit.\n" % a.rev,
           "// The core functions as they were before the performance work, kept so the optimised ones can be tested against them (test/test_core.cpp).\n",
           "#pragma once\n#include <math.h>\n#include <stdint.h>\n#include <string.h>\n\n#include \"core.h\"\n\nnamespace legacy {\nusing namespace fwb;\n\n",
           EXTRA_STRUCT, "\n"]
    for name in WANTED:
        body = cut(src, name)
        body = re.sub(r"^static\s+", "static ", body)
        out.append(body + "\n\n")
    out.append("}  // namespace legacy\n")
    path = os.path.join(ROOT, "test", "legacy_core.h")
    open(path, "w", newline="\n").write("".join(out))
    print("wrote", path, "(%d functions from %s)" % (len(WANTED), a.rev))


if __name__ == "__main__":
    main()
