#!/usr/bin/env python3
"""Generate golden test vectors from the Python reference implementation.

    python tools/make_golden.py            ->  test/golden.txt

The C++ firmware core (test/test_core.cpp) and the JavaScript analysis code (test/test_analysis.js)
must reproduce these. Entries are compared as zone-weight vectors (so 'zone 2 at f=255' equals
'zone 3 at f=0'), with a small tolerance for float rounding; the distance byte d may differ by 2.
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from reference import govee, layout, protocol  # noqa: E402


def ent(entries):
    return " ".join("%d,%d,%d,%d" % tuple(e) for e in entries)


def main():
    rnd = random.Random(12345)
    lines = ["# generated by tools/make_golden.py - do not edit"]

    # --- frame decoding -------------------------------------------------------
    for i in range(40):
        zones = [tuple(rnd.randrange(256) for _ in range(3)) for _ in range(24)]
        key = bytes(rnd.randrange(256) for _ in range(3 + i % 8))
        frame = protocol.encode_frame(zones, key)
        assert protocol.decode_frame(frame) == zones
        flat = "".join("%02x%02x%02x" % z for z in zones)
        lines.append("DECODE %s %s" % (frame.hex(), flat))
    good = protocol.encode_frame([(1, 2, 3)] * 24, bytes([9, 8, 7]))
    bad = [good[:-1], bytes([good[0] ^ 1]) + good[1:], good[:3] + bytes([good[3] ^ 1]) + good[4:],
           good[:11] + bytes([good[11] ^ 0x40]) + good[12:],      # marker byte corrupted (key is 3 bytes, data starts at 11)
           b"", bytes(90)]
    for b in bad:
        assert protocol.decode_frame(b) is None
        lines.append("DECODE %s -" % (b.hex() or "00"))

    # --- classifying datagrams (understood / new payload layout / unreadable) -----------
    def fix_checksum(d):
        d = bytearray(d)
        d[5] = (167 + sum(d) - d[3] - d[5]) & 255
        return bytes(d)

    def change_marker(d, new):
        q = len(d) - 83
        d = bytearray(d)
        for i, b in enumerate(new):
            d[8 + q + i] = b ^ d[8 + (i % q)]
        return fix_checksum(d)

    def grow(d, extra_zones):
        q = len(d) - 83
        pt = bytes(b ^ d[8 + (i % q)] for i, b in enumerate(d[8 + q:])) + bytes(3 * extra_zones)
        out = bytearray(d[:8 + q]) + bytes(b ^ d[8 + (i % q)] for i, b in enumerate(pt))
        out[3] = len(out) - 5
        return fix_checksum(out)

    def classify_line(d):
        cls, cs, head, _ = protocol.classify_frame(d)
        return "CLASSIFY %s %d %d %s" % (d.hex() or "00", cls, int(cs), head.hex() if head else "-")

    samples = []
    for i in range(24):                                              # real-looking frames, every key length
        zones = [tuple(rnd.randrange(256) for _ in range(3)) for _ in range(24)]
        samples.append(protocol.encode_frame(zones, bytes(rnd.randrange(256) for _ in range(3 + i % 8))))
    ok_frames = list(samples)
    for d in ok_frames[:4]:
        samples.append(d[:5] + bytes([d[5] ^ 0x55]) + d[6:])         # wrong checksum: still decodes
    for d in ok_frames[:8]:
        samples.append(change_marker(d, b"\x08\x06\x06"))            # a different marker, valid checksum
        samples.append(change_marker(d, b"\x06\x04\x07"))
    d = ok_frames[3]
    samples.append(change_marker(d, b"\x08\x06\x06")[:5] + b"\x00" + change_marker(d, b"\x08\x06\x06")[6:])   # new marker and a wrong checksum
    for d in ok_frames[:6]:
        samples.append(grow(d, 2))                                   # a bigger payload: size outside 86-93, framing and checksum valid
        samples.append(grow(d, 8))
    d = ok_frames[1]
    samples += [b"\x56" + d[1:], d[:3] + bytes([d[3] + 1]) + d[4:], d[:-1], d + b"\x00", d[:5], b"", bytes(90), bytes(rnd.randrange(256) for _ in range(90)),
                b"\x55\xaa\x5a" + bytes([255 - 5 + 1]) + bytes(300), d[:2]]
    for d in samples:
        lines.append(classify_line(d))

    # --- uv -> entry (with distance beyond the TV) --------------------------------
    pts = [(round(-0.3 + 0.1 * i, 6), round(-0.3 + 0.1 * j, 6)) for i in range(17) for j in range(17)]
    pts += [(round(rnd.uniform(-1.5, 2.5), 6), round(rnd.uniform(-0.8, 1.8), 6)) for _ in range(250)]   # same precision as printed
    for u, v in pts:
        if 0 < u < 1 and 0 < v < 1:                  # skip points equally close to two edges (tie-break is arbitrary)
            d = sorted((v, 1 - v, u, 1 - u))
            if d[1] - d[0] < 1e-3:
                continue
        lines.append("UV %.6f %.6f %d,%d,%d,%d" % ((u, v) + tuple(layout.uv_to_entry(u, v))))

    # --- manual layouts ---------------------------------------------------------
    edges = ["top", "right", "bottom", "left"]
    for count, side, span, edge in [(150, "left", None, "top"), (150, "right", None, "top"), (210, "left", (91, 174), "top"),
                                    (210, "right", (30, 120), "top"), (84, "left", (0, 83), "top"), (1, "left", None, "top"),
                                    (6, "left", None, "top"), (210, "left", (83, 163), "top"), (210, "left", (83, 163), "bottom"),
                                    (210, "right", (40, 130), "bottom"), (180, "left", (30, 120), "left"), (180, "right", (30, 120), "left"),
                                    (180, "left", (50, 140), "right"), (180, "right", (50, 140), "right"), (100, "left", None, "bottom"),
                                    (100, "left", None, "right")]:
        e = layout.table_linear(count, side, span, edge=edge)
        lines.append("LINEAR %d %d %d %d %d %s" % (count, side == "right", span[0] if span else -1, span[1] if span else -1, edges.index(edge), ent(e)))
    for count in (142, 200, 215, 60):
        for corner in ("top-left", "top-right", "bottom-right", "bottom-left"):
            for direction in ("clockwise", "counterclockwise"):
                for shift in (0, 5):
                    e = layout.table_loop(count, corner, direction, None, shift, (16, 9))
                    lines.append("LOOP %d %d %d auto %d 16 9 %s" % (
                        count, ["top-left", "top-right", "bottom-right", "bottom-left"].index(corner),
                        direction == "counterclockwise", shift, ent(e)))
    e = layout.table_loop(142, "bottom-right", "counterclockwise", (46, 25, 46, 25), 0, (16, 9))
    lines.append("LOOP 142 2 1 46,25,46,25 0 16 9 %s" % ent(e))

    # --- which zones a target follows (the picture map) ---------------------------------
    for count, side, span, edge in [(150, "left", None, "top"), (210, "left", (82, 172), "top"), (266, "left", None, "right"), (100, "right", (20, 80), "bottom"),
                                    (180, "left", (30, 120), "left"), (7, "left", None, "top")]:
        tbl = layout.table_linear(count, side, span, edge=edge)
        u = layout.zone_usage(tbl)
        lines.append("USAGE LINEAR %d %d %d %d %d %s" % (count, side == "right", span[0] if span else -1, span[1] if span else -1, edges.index(edge), " ".join("%.3f" % x for x in u)))
    for count, corner, direction in [(142, "top-left", "clockwise"), (200, "bottom-right", "counterclockwise")]:
        tbl = layout.table_loop(count, corner, direction, None, 0, (16, 9))
        u = layout.zone_usage(tbl)
        lines.append("USAGE LOOP %d %d %d %s" % (count, ["top-left", "top-right", "bottom-right", "bottom-left"].index(corner), direction == "counterclockwise", " ".join("%.3f" % x for x in u)))

    # --- applying a table to zone colours, with smoothing beyond the TV ---------------
    for case in range(8):
        zones = [[float(rnd.randrange(256)) for _ in range(3)] for _ in range(24)]
        tbl = layout.table_linear(210, "left", (91, 174))
        pct = [0, 100, 50, 100, 25, 100, 75, 100][case]
        info = layout.smooth_info(tbl, pct)
        cols = layout.apply_table(tbl, zones, info)
        flat_z = ",".join("%.3f" % z[c] for z in zones for c in range(3))
        sample = [0, 10, 40, 80, 91, 100, 130, 174, 175, 190, 209]
        lines.append("APPLY 210 left 91 174 %d %d %d %s | %s" % (pct, info[2], info[3], flat_z, " ".join("%d:%.3f,%.3f,%.3f" % ((i,) + tuple(cols[i])) for i in sample)))

    # --- vivid blending of two colours, and a whole table with it -----------------------------
    pairs = [((255, 0, 0), (0, 255, 0)), ((255, 0, 0), (0, 0, 255)), ((0, 255, 0), (0, 0, 255)), ((80, 4, 153), (150, 130, 45)), ((101, 0, 142), (67, 112, 117)),
             ((200, 200, 200), (255, 0, 0)), ((0, 0, 0), (0, 200, 100)), ((90, 90, 90), (40, 40, 40)), ((255, 0, 0), (0, 255, 255)), ((255, 128, 0), (255, 128, 0)),
             ((250, 10, 5), (10, 5, 250)), ((20, 240, 20), (240, 20, 240))]
    for _ in range(8):
        pairs.append((tuple(float(rnd.randrange(256)) for _ in range(3)), tuple(float(rnd.randrange(256)) for _ in range(3))))
    for pa, pb in pairs:
        for w in (0.0, 0.25, 0.5, 0.75, 1.0):
            o = layout.blend_vivid(list(pa), list(pb), w)
            lines.append("VBLEND %s %s %.4f %.3f %.3f %.3f" % (",".join("%.3f" % v for v in pa), ",".join("%.3f" % v for v in pb), w, o[0], o[1], o[2]))
    for case in range(3):
        zones = [[float(rnd.randrange(256)) for _ in range(3)] for _ in range(24)]
        tbl = layout.table_linear(210, "left", (91, 174))
        info = layout.smooth_info(tbl, [100, 50, 0][case])
        cols = layout.apply_table(tbl, zones, info, vivid=True)
        flat_z = ",".join("%.3f" % z[c] for z in zones for c in range(3))
        sample = [0, 10, 40, 80, 91, 100, 130, 174, 175, 190, 209]
        lines.append("APPLYV 210 left 91 174 %d %d %d %s | %s" % ([100, 50, 0][case], info[2], info[3], flat_z, " ".join("%d:%.3f,%.3f,%.3f" % ((i,) + tuple(cols[i])) for i in sample)))

    # --- DDP header -------------------------------------------------------------
    for seq, dt, off, ln, push in [(1, 0x0B, 0, 450, 1), (15, 0x1B, 40, 1440, 0), (3, 0x0B, 100000, 7, 1)]:
        hdr = struct.pack("!BBBBIH", 0x40 | (1 if push else 0), seq, dt, 1, off, ln)
        lines.append("DDP %d %d %d %d %d %s" % (seq, dt, off, ln, push, hdr.hex()))

    # --- sharper zone edges: a table, then the same table sharpened ---------------------------
    # (the input table is part of the vector, so both sides sharpen exactly the same entries)
    for count, side, span, edge in [(210, "left", (91, 174), "top"), (150, "left", None, "top"), (266, "left", None, "right"), (100, "right", (20, 80), "bottom"), (42, "right", None, "bottom")]:
        src = layout.table_linear(count, side, span, edge=edge)
        for pct in (25, 50, 80, 100):
            lines.append("SHARP %d %s | %s" % (pct, ent(src), ent(layout.sharpen(src, pct))))
    src = layout.table_loop(142, "top-left", "clockwise", None, 0, (16, 9))
    for pct in (30, 60, 100):
        lines.append("SHARP %d %s | %s" % (pct, ent(src), ent(layout.sharpen(src, pct))))

    # --- Govee streaming packets (the complete UDP payload) ----------------------
    for on in (1, 0):
        lines.append("GOVEE ENABLE %d %s" % (on, govee.enable_json(bool(on))))
    for n in (1, 2, 5, 20, 33, 60):
        rgb = [tuple(rnd.randrange(256) for _ in range(3)) for _ in range(n)]
        lines.append("GOVEE FRAME %d %s %s" % (n, "".join("%02x%02x%02x" % px for px in rgb), govee.frame_json(rgb)))

    out = os.path.join(HERE, "..", "test", "golden.txt")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d lines)" % (os.path.normpath(out), len(lines)))


if __name__ == "__main__":
    main()
